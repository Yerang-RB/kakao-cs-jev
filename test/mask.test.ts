import { test } from "node:test";
import assert from "node:assert/strict";
import { mask } from "../src/mask.js";

test("휴대전화: 하이픈·공백·점·붙여쓴 변형", () => {
  assert.equal(mask("번호 010-1234-5678 입니다"), "번호 010-****-5678 입니다");
  assert.equal(mask("010 1234 5678"), "010-****-5678");
  assert.equal(mask("010.1234.5678"), "010-****-5678");
  assert.equal(mask("전화01112345678로 주세요"), "전화011-****-5678로 주세요");
  assert.equal(mask("016-123-4567"), "016-****-4567");
});

test("이메일", () => {
  assert.equal(mask("메일은 hong.gil@example.com 이에요"), "메일은 h***@example.com 이에요");
  assert.equal(mask("a_b+x@mail.co.kr"), "a***@mail.co.kr");
});

test("계좌: 10~14자리 숫자·하이픈", () => {
  assert.equal(mask("국민 123456-01-234567로 보내 주세요"), "국민 ****로 보내 주세요");
  assert.equal(mask("계좌 1002345678901"), "계좌 ****");
  assert.equal(mask("3333-01-2345678"), "****");
});

test("음성: 방ID 16자리·URL·날짜·짧은 숫자는 그대로", () => {
  for (const s of [
    "방 4000000000000048",
    "https://business.kakao.com/space/000000/channel/_XXXXX/chats/4000000000000048?t=1234567890&m=a@b.com",
    "2026-09-24에 반납",
    "3대 12000원",
    "주문번호 A1234567890B",
    "20260926 1430 예약", // 날짜+시각(메타 REVIEW 참고 1 회귀)
    "20260926 3대 부탁드려요",
    "예약 20260926 1430",
  ])
    assert.equal(mask(s), s);
});

test("R4: 카드 4-4-4-4(하이픈·공백) → ****, 구분자 없는 16자리 방ID는 그대로", () => {
  assert.equal(mask("카드 1234-5678-9012-3456 결제"), "카드 **** 결제");
  assert.equal(mask("1234 5678 9012 3456"), "****");
  assert.equal(mask("방 4000000000000048"), "방 4000000000000048");
});

test("R4: 공백 구분 계좌 → ****, 공백 구분 가격은 그대로", () => {
  assert.equal(mask("신한 123 456 789012로"), "신한 ****로");
  assert.equal(mask("1000 2000 3000원"), "1000 2000 3000원");
  assert.equal(mask("계좌 1002345678901 1 2"), "계좌 **** 1 2");
});

test("R4: 영문 접두 전화·전각 숫자·유선", () => {
  assert.equal(mask("tel010-1234-5678"), "tel010-****-5678");
  assert.equal(mask("HP01012345678"), "HP010-****-5678");
  assert.equal(mask("０１０-１２３４-５６７８"), "010-****-5678");
  assert.equal(mask("매장 02-123-4567 로"), "매장 02-***-4567 로");
  assert.equal(mask("031-1234-5678"), "031-****-5678");
});

test("R4 음성: 날짜·URL 통째·한글 로컬파트 이메일은 그대로", () => {
  for (const s of ["2026-09-25", "2026-02-15 반납", "https://x.kr/a/02-123-4567/1234-5678-9012-3456"]) assert.equal(mask(s), s); // 한글 로컬파트 이메일은 B9에서 가리게 바뀜
});

test("회귀(리뷰 F1): 앞에 숫자 토큰이 있는 공백 구분 휴대전화", () => {
  assert.equal(mask("1 010 1234 5678"), "1 010-****-5678");
  assert.equal(mask("12 34 010 1234 5678"), "12 34 010-****-5678");
  assert.equal(mask("9/25 010 1234 5678 로"), "9/25 010-****-5678 로");
  assert.equal(mask("1 2 010 1234 5678"), "1 2 010-****-5678");
});

test("보안 회수 F: 공백 2묶음 주민번호·점 구분 카드·전각/마이너스/장음/밑줄 구분 휴대전화", () => {
  assert.equal(mask("900101 1234567"), "****");
  assert.equal(mask("주민 900101 1234567 입니다"), "주민 **** 입니다");
  assert.equal(mask("카드 1234.5678.9012.3456"), "카드 ****");
  for (const s of ["010－1234－5678", "010−1234−5678", "010ー1234ー5678", "010_1234_5678", "０１０－１２３４－５６７８"])
    assert.equal(mask(s), "010-****-5678", s);
  assert.equal(mask("12345 67890"), "****"); // 알려진 천장: 10자리 2묶음은 계좌형으로 본다(원장 R4)
});

test("보안 회수 F 음성: 2묶음이라도 합산 10자리 미만·5자리 묶음 없음·하이픈 낀 기간은 그대로", () => {
  for (const s of ["2026 0925", "1234 5678", "3 - 5일", "1000 2000원", "12 3456789", "2026.09.25", "1.2.3.4"]) assert.equal(mask(s), s);
});

// B9(리뷰 S4, 3모델 보안 패스 2026-09-29): 세 리포트가 실측한 미탐 형식 전부. [입력, 출력에 남으면 안 되는 부분].
// 예외 하나 — URL 속 번호(「https://x.com/?p=01012345678」)는 R4 결정대로 URL을 통째 건너뛴다(위 R4 음성).
const B9: [string, string][] = [
  ["010/1234/5678", "1234"], ["010,1234,5678", "1234"], ["010~1234~5678", "1234"],
  ["(010) 1234-5678", "1234"], ["010)1234-5678", "1234"], ["010(1234)5678", "1234"],
  ["010\n1234\n5678", "1234"], ["010\u200b1234\u200b5678", "1234"],
  ["010\u20101234\u20105678", "1234"], ["010\u20111234\u20115678", "1234"], ["010ㅡ1234ㅡ5678", "1234"],
  ["010  1234  5678", "1234"], ["010 1234  5678", "1234"],
  ["8210 1234 5678", "1234"],
  ["900101－1234567", "1234567"], ["900101 - 1234567", "1234567"], ["12 34 900101 1234567", "1234567"],
  ["110 - 123 - 456789", "456789"],
  ["카드 4111111111111111 로 결제", "41111111"], ["3782 822463 10005", "822463"], ["국민 1234 5678 90 12", "5678"],
  ["hong＠gmail.com", "ong"], ["홍길동@naver.com 으로", "길동"], ["hong @ gmail.com", "ong"],
  ["(02)123-4567 로 전화", "123"], ["(02) 123-4567", "123"], ["02)123-4567", "123"],
];

test("B9: 리뷰 3곳의 미탐 형식은 모두 가린다(정규화 — NFKC·제로폭 제거·괄호 지역번호·구분자 묶음·Luhn 카드·한글/띄운 이메일)", () => {
  for (const [x, secret] of B9) {
    const out = mask(x);
    assert.ok(!out.includes(secret), `${JSON.stringify(x)} → ${JSON.stringify(out)}`);
  }
});

test("B9 음성: 날짜·시각·가격·짧은 목록·방ID(Luhn 실패 16자리)는 그대로", () => {
  for (const s of ["20260926 1430", "2026.10.01", "10/02 반납", "3 - 5일", "1, 2, 3", "2만 5천 원", "방 4000000000000048", "1000/2000/3000원"]) assert.equal(mask(s), s, s);
});
