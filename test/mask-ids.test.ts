// maskIds(리뷰 B10): DB에 남기는 텍스트에서 주민등록번호·카드번호만 가린다. 전화·계좌·이메일·날짜·주문번호는 원문(상담에 필요).
import { test } from "node:test";
import assert from "node:assert/strict";
import { maskIds } from "../src/mask.js";

const R = "******-*******", C = "****-****-****-****";

test("주민번호: 하이픈·공백·대시·붙여 씀·전각 숫자 → 가림, 앞뒤 문장은 그대로", () => {
  for (const [i, o] of [
    ["주민번호 900101-1234567 입니다", `주민번호 ${R} 입니다`],
    ["900101 - 2234567", R],
    ["900101–1234567", R],
    ["9001011234567로 조회", `${R}로 조회`],
    ["９００１０１－１２３４５６７", R],
    ["앞 001231-3234567\n뒤", `앞 ${R}\n뒤`],
  ]) assert.equal(maskIds(i), o, i);
});

test("카드번호: 4-4-4-4(하이픈·공백·점)·붙여 쓴 16자리·15자리(Luhn 통과) → 가림", () => {
  for (const [i, o] of [
    ["카드 4111-1111-1111-1111 결제", `카드 ${C} 결제`],
    ["4111 1111 1111 1111", C],
    ["5500.0000.0000.0004", C],
    ["4111111111111111", C],
    ["아멕스 378282246310005", `아멕스 ${C}`],
    ["3782 822463 10005", C],
  ]) assert.equal(maskIds(i), o, i);
});

test("가리지 않는 것: 전화·계좌·이메일·날짜·시각·Luhn 실패 16자리·날짜가 아닌 13자리·URL 속 숫자", () => {
  for (const s of [
    "010-1234-5678로 연락 주세요",
    "국민 123456-78-901234 로 입금",
    "a@b.com",
    "20261001 1430",
    "주문번호 1234567890123456",
    "9913451234567",
    "https://example.com/item/4111111111111111x",
    "2026-10-01 오후 4:54",
  ]) assert.equal(maskIds(s), s, s);
});
